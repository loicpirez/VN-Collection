import Database from 'better-sqlite3';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

function convertTable(sql) {
  return sql
    .replace(/\/\*\*[\s\S]*?\*\//g, '')
    .replace(/^CREATE TABLE\s+/i, 'CREATE TABLE IF NOT EXISTS ')
    .replace(/INTEGER\s+PRIMARY KEY\s+AUTOINCREMENT/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bINTEGER\b/gi, 'BIGINT')
    .replace(/\bREAL\b/gi, 'DOUBLE PRECISION')
    .replace(/\s+,/g, ',')
    .trim();
}

function convertIndex(sql) {
  return sql
    .replace(/^CREATE\s+(UNIQUE\s+)?INDEX\s+/i, (_match, unique) => `CREATE ${unique ?? ''}INDEX IF NOT EXISTS `)
    .replace(/([a-zA-Z_][a-zA-Z0-9_]*)\s+COLLATE\s+NOCASE/gi, 'LOWER($1)')
    .trim();
}

function statement(sql) {
  return sql.endsWith(';') ? sql : `${sql};`;
}

const sourcePath = resolve(process.argv[2] ?? 'data/collection.db');
const outputPath = resolve(process.argv[3] ?? 'db/postgres/migrations/0001_baseline.sql');
const source = new Database(sourcePath, { readonly: true, fileMustExist: true });

try {
  const tables = source.prepare(`
    SELECT name, sql
    FROM sqlite_master
    WHERE type = 'table'
      AND name NOT LIKE 'sqlite_%'
      AND sql IS NOT NULL
    ORDER BY rowid
  `).all();
  const indexes = source.prepare(`
    SELECT name, sql
    FROM sqlite_master
    WHERE type = 'index'
      AND name NOT LIKE 'sqlite_%'
      AND sql IS NOT NULL
    ORDER BY rowid
  `).all();
  const tableNames = new Set(tables.map((row) => row.name));
  const sections = [
    '-- Generated by scripts/generate-postgres-baseline.mjs.',
    '-- Source schema is read-only; review this migration before production use.',
    'BEGIN;',
    '',
    ...tables.map((row) => statement(convertTable(row.sql))),
  ];
  if (!tableNames.has('app_job_lock')) {
    sections.push(
      statement(`CREATE TABLE IF NOT EXISTS app_job_lock (
        name TEXT PRIMARY KEY,
        owner TEXT NOT NULL,
        expires_at BIGINT NOT NULL
      )`),
    );
  }
  sections.push(
    '',
    ...indexes.map((row) => statement(convertIndex(row.sql))),
    statement('CREATE INDEX IF NOT EXISTS idx_app_job_lock_expiry ON app_job_lock(expires_at)'),
    '',
    statement(`CREATE TABLE IF NOT EXISTS schema_migration (
      version TEXT PRIMARY KEY,
      applied_at BIGINT NOT NULL
    )`),
    statement(`INSERT INTO schema_migration (version, applied_at)
      VALUES ('0001_baseline', (EXTRACT(EPOCH FROM clock_timestamp()) * 1000)::BIGINT)
      ON CONFLICT (version) DO NOTHING`),
    '',
    'COMMIT;',
    '',
  );
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, sections.join('\n'), 'utf8');
  process.stdout.write(`Generated ${outputPath} with ${tables.length + (tableNames.has('app_job_lock') ? 0 : 1)} tables and ${indexes.length + 1} indexes.\n`);
} finally {
  source.close();
}
